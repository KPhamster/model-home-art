// Exports the site's photos for the web.
//
// Source: the full-size originals in assets/ (some are 6 MB and 6,000 px tall).
// Output:
//   public/photos/<name>-<width>.webp   each photo at a few widths
//   src/lib/photos.ts                   the list the <Photo> component reads
//
// The pages used to import the originals directly, so every visitor downloaded them at
// full size. Now each photo is served as a small WebP, at the width the screen needs.
//
// To add or replace a photo: put the original in assets/, add a line to PHOTOS below,
// and run:  npm run photos
// Uses sharp, which is installed with Next.js.

import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "assets");
const outDir = path.join(root, "public/photos");
const manifestPath = path.join(root, "src/lib/photos.ts");

const LADDER = [320, 480, 720, 960, 1280, 1920]; // widths a photo may be exported at
const WEBP = { quality: 78, effort: 5 };

// Widest export each kind of photo needs: about twice the widest it is ever drawn.
const CARD = 960; // category cards, drawn up to ~440 px wide
const HALF = 1280; // photos that fill half the page, drawn up to ~700 px wide
const FULL = 1920; // full-width backgrounds

// name (used in the pages) -> [original in assets/, widest export]
const PHOTOS = {
  jersey: ["jersey_image.png", CARD],
  mirror: ["mirror_image.jpeg", CARD],
  diploma: ["diploma_image.jpeg", CARD],
  "fine-art": ["fine_art_image.jpg", CARD],
  poster: ["poster_image.jpeg", CARD],
  photo: ["photo_image.png", CARD],
  "canvas-stretching": ["canvas_stretching_image.png", CARD],
  needlework: ["needlework_image.png", CARD],
  memorabilia: ["memorabilia_image.png", CARD],
  medals: ["medals_image.jpeg", CARD],
  album: ["album_image.jpeg", CARD],
  "baby-keepsake": ["babykeepsake_image.jpeg", CARD],
  wedding: ["wedding_image.jpeg", CARD],
  military: ["military_image.jpeg", CARD],
  sports: ["sports_image.jpeg", CARD],
  document: ["document_image.jpeg", CARD],
  map: ["map_image.jpeg", CARD],
  flags: ["flags_image.jpeg", CARD],
  "visit-our-shop": ["visit_our_shop_image.jpg", HALF],
  business: ["business_image.png", HALF],
  "call-to-action": ["calltoaction_image.jpg", FULL],
};

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const entries = [];
let originalBytes = 0;
let exportedBytes = 0;

for (const [name, [file, widest]] of Object.entries(PHOTOS)) {
  const source = path.join(sourceDir, file);
  originalBytes += (await stat(source)).size;
  // rotate() with no angle turns the picture the way its camera data says it was taken.
  const upright = sharp(source).rotate();
  const { info } = await upright.clone().toBuffer({ resolveWithObject: true });
  const limit = Math.min(widest, info.width);
  const widths = LADDER.filter((w) => w < limit);
  widths.push(limit); // the widest export is the limit itself, never an enlargement

  const sizes = [];
  for (const w of widths) {
    const buffer = await upright.clone().resize({ width: w, kernel: "lanczos3" }).webp(WEBP).toBuffer();
    await writeFile(path.join(outDir, `${name}-${w}.webp`), buffer);
    exportedBytes += buffer.length;
    sizes.push(`${w}: ${Math.round(buffer.length / 1024)} KB`);
  }
  // Proportions of the picture, as width and height of its widest export.
  entries.push({ name, width: limit, height: Math.round((limit * info.height) / info.width), widths });
  console.log(`${name.padEnd(18)} ${`${info.width}x${info.height}`.padEnd(11)} -> ${sizes.join(", ")}`);
}

const manifest = `// Generated by scripts/build-photos.mjs. Do not edit by hand; run "npm run photos".

/**
 * The site's photos. Each is exported to /public/photos as <name>-<width>.webp at the
 * widths listed; width and height are the proportions of the picture.
 */
export const photos = {
${entries.map((e) => `  ${JSON.stringify(e.name)}: { width: ${e.width}, height: ${e.height}, widths: ${JSON.stringify(e.widths)} },`).join("\n")}
} as const;

export type PhotoName = keyof typeof photos;
`;
await writeFile(manifestPath, manifest);

const mb = (bytes) => (bytes / 1048576).toFixed(1);
console.log(`\n${entries.length} photos: originals ${mb(originalBytes)} MB, all exports together ${mb(exportedBytes)} MB`);
